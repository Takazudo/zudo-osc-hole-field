#!/usr/bin/env python3
"""Freeze the pre-adoption JL/JR/K slots as the adopted placement-pin input (decision E15).

Minimal-move reflow after the S2b adoption: every free package whose footprint is unchanged
keeps the slot it had in the pre-adoption floorplan, so its routed copper stays valid. Swapped
packages and added packages are left free; the floorplan first tries each swapped IC on its old
slot next to its pinned bypass capacitors and releases those capacitors only when it cannot fit.
Run once from the baseline commit; the output is a reviewed source input, not regenerated by
regen-all.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.checks.connector_packing35 import board_for

OUT = ROOT / 'design/partition/adopted-placement-pins.json'
BOARDS = ('JL', 'JR', 'K')
RB4413 = 'circuit/routing/issue189/jr-rb4413-edge-bridge/pending-source-translation.json'


def blob(commit, path):
    return subprocess.run(['git', '-C', str(ROOT), 'show', f'{commit}:{path}'], check=True, capture_output=True).stdout


def build(baseline):
    old_io = json.loads(blob(baseline, 'design/reports/io-partition.json'))
    floor_bytes = blob(baseline, 'design/partition/floorplan-candidate.json')
    old_rows = {r['ref']: r for r in json.loads(floor_bytes)['placements']}
    new_io = json.loads((ROOT / 'design/reports/io-partition.json').read_text())
    old = {p['ref']: p for p in old_io['physical_packages']}
    new = {p['ref']: p for p in new_io['physical_packages']}
    swapped = {r for r, p in new.items() if r in old and old[r]['footprint'] != p['footprint']}
    pins = []
    for ref in sorted(new):
        p = new[ref]
        if p['panel_uid'] or board_for(p) not in BOARDS:
            continue
        if ref not in old or ref in swapped:
            continue
        row = old_rows[ref]
        if row['board'] != board_for(p) or old[ref]['footprint'] != p['footprint']:
            raise ValueError('baseline row does not match the adopted package: ' + ref)
        pins.append({'footprint': p['footprint'], **{k: v for k, v in row.items() if k != 'kicad_orientation_deg'}})
    reservation = next(c for c in json.loads((ROOT / RB4413).read_text())['translations'] if c['ref'] == 'RB4413')
    return {
        'schema_version': 2,
        'status': 'ADOPTED placement-pin input (decision E15, S2b adoption 2026-11-01); source geometry only',
        'rule': 'Every free JL/JR/K package whose footprint is unchanged keeps its pre-adoption slot. A swapped IC is tried on its '
                'old slot (same face, four rotations) beside its pinned bypass capacitors within the bypass limit; when no rotation '
                'fits, the IC and its capacitors are released. Released and added packages are placed by the locality placer around the pins.',
        'baseline': {'commit': baseline, 'floorplan': 'design/partition/floorplan-candidate.json',
                     'floorplan_sha256': hashlib.sha256(floor_bytes).hexdigest()},
        'generated_by': 'scripts/checks/build_adopted_placement_pins.py',
        'counts': {b: sum(1 for p in pins if p['board'] == b) for b in BOARDS},
        'free_swapped': sorted(swapped & {r for r in new if board_for(new[r]) in BOARDS}),
        'swapped_slots': [{'old_footprint': old[r]['footprint'], **{k: v for k, v in old_rows[r].items() if k != 'kicad_orientation_deg'}}
                          for r in sorted(swapped) if board_for(new[r]) in BOARDS],
        'reservations': [{'ref': 'RB4413', 'source': RB4413, 'delta_mm': reservation['delta_mm'],
                          'reason': 'issue189 jr-rb4413-edge-bridge native evidence binds RB4413 to this slot; the pending 0.2 mm translation target stays reserved.'}],
        'pins': pins,
    }


def main():
    a = argparse.ArgumentParser(); a.add_argument('--baseline', default='539ff382'); args = a.parse_args()
    data = build(args.baseline)
    OUT.write_text(json.dumps(data, indent=1) + '\n')
    print('PASS: adopted placement pins', data['counts'], 'free swapped', len(data['free_swapped']))


if __name__ == '__main__':
    main()
