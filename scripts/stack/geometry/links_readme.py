"""Render design/stack/geometry/links/README.md from the link candidate; headings carry the computed verdicts."""

JOINTS = ('JL-K', 'JR-K', 'P-K', 'JL-P via K')
FOCUS = ('P100-N20 G-PER-2S', 'P100-N20 G-BETWEEN')


def _fmt(v):
    return '-' if v is None else ('%.1f' % v if isinstance(v, float) else str(v))


def _xy(v):
    return '(%.1f, %.1f)' % tuple(v)


def _option_row(s):
    lb = sum(v['lower_bound'] for v in s['lower_bound_per_joint'].values())
    k = s['K_displaced']
    f = s['front_displaced']
    need = s['cable_needed_mm']
    return '| %s | %s | %d | %s | %d | %d (%.2f %%) | %d / %d | %d / %d | **%d** / %d | %d / %d / %d | %d | %s | %d of %d | %d |' % (
        s['option'], s['signals_per_link'], s['links'], ' / '.join(str(s['links_per_joint'][j]) for j in JOINTS), lb,
        s['slots'], s['slot_area_share_of_K_pct'], k['by_slots'], k['by_fields_only'], k['F.Cu'], k['B.Cu'],
        k['total'], k['rigid_return_criterion'], f['JL'], f['JR'], f['P'], s['unplaced'],
        '%.1f to %.1f' % tuple(need) if need else '-', s['links_served_by_cable'], s['placed'], s['latch_not_shown'])


def render(out, small=None):
    summ = {s['option']: s for s in out['summary']}
    c = out['site_counts']
    f4 = out['f4_reproduction']
    rig = out['rigid_return_criterion']
    head = summ[FOCUS[0]]
    sp = out['search_parameters']
    nopt = len(out['summary'])
    over = [s['option'] for s in out['summary'] if s['K_displaced']['total'] > s['K_displaced']['rigid_return_criterion']]
    short_opts = [s['option'] for s in out['summary'] if s['unplaced']]
    L = []
    w = L.append
    w('# Flat-link option study (ST-02): %s, and %d of %d options displace more K footprints than the rigid return '
      'criterion of %d' % ('%d of %d options leave links without a legal place' % (len(short_opts), nopt) if short_opts
                           else 'every option places every link', len(over), nopt, rig['total']))
    w('')
    w('Generated by `python3 scripts/stack/geometry/links.py` from the retained rigid candidate '
      '(`../stack-candidate.json`), the board files and `link-options.json`; do not edit by hand. '
      'Status: option study on unvalidated drafts, courtyard level only. Nothing here is a copper clearance, a tolerance '
      'result or a fit, and nothing is selected, adopted or bought. Every parameter carries its status word in '
      '`link-options.json`; every count below is DERIVED from retained files with those parameters.')
    w('')
    by = c['by_family']
    f4sig = out['da03_f4_signals']
    diff = [(fam, e['signals'], f4sig[fam]) for fam, e in by.items() if e['signals'] != f4sig[fam]]
    w('## %d pairs with %d positions and %d signals go to links; %s'
      % (c['pairs'], c['positions'], c['signals'],
         '; '.join('%s carries %d signals, not the %d of section F4' % d for d in diff) if diff
         else 'every family reproduces the signals of section F4'))
    w('')
    w('| Family (joint) | Pairs | Positions | Signals | DA-03 F4 signals |')
    w('| --- | --- | --- | --- | --- |')
    for fam, e in by.items():
        w('| %s | %d | %d | %d | %d |' % (fam, e['pairs'], e['positions'], e['signals'], f4sig[fam]))
    w('| **Total** | **%d** | **%d** | **%d** | %d |' % (c['pairs'], c['positions'], c['signals'], sum(f4sig.values())))
    w('')
    short = c['sites_below_family_maximum']
    if short:
        w('Sites that carry fewer signals than the others of their family (DERIVED from the retained pin maps): %s. '
          'Reported, not adjusted.' % '; '.join('%s (%s): %d of %d, %s' % (x['site'], x['family'], len(x['signals']),
                                                                         x['family_maximum'], ', '.join('`%s`' % n for n in x['signals']))
                                                for x in short))
        w('')
    w('')
    pj = f4['per_joint']
    ref = f4['da03_f4']
    rep_j = [j for j in JOINTS if pj[j]['links'] == ref[j][0] and _fmt(pj[j]['mean_site_distance_mm']) == _fmt(ref[j][2])
             and _fmt(pj[j]['max_site_distance_mm']) == _fmt(ref[j][3])]
    not_j = [j for j in JOINTS if j not in rep_j]
    w('## Clustering at %d positions gives %d links against the %d of section F4: %s reproduce%s'
      % (f4['capacity_positions'], f4['total_links'], sum(v[0] for v in ref.values()), ', '.join(rep_j) or 'no joint',
         ', %s do not' % ', '.join(not_j) if not_j else ''))
    w('')
    w('| Joint | Sites | Links (F4) | Lower bound (F4) | Site distance mean / largest, mm |')
    w('| --- | --- | --- | --- | --- |')
    for j in JOINTS:
        v = pj[j]
        w('| %s | %d | %d (%d) | %d (%d) | %s / %s |' % (j, v['sites'], v['links'], f4['da03_f4'][j][0], v['lower_bound'],
                                                     f4['da03_f4'][j][1], _fmt(v['mean_site_distance_mm']),
                                                     _fmt(v['max_site_distance_mm'])))
    w('')
    w('F4 does not retain its clustering rule. This study clusters per joint and front board with a greedy rule and a '
      'join radius of %s mm (ASSUMED; chosen in attempt a4 as the smallest scanned radius that reproduced the most F4 '
      'joints). %s'
      % (_fmt(sp['join_radius_mm']), ' '.join('%s gives %d links against %d, distances %s / %s mm against %s / %s mm.'
                                              % (j, pj[j]['links'], ref[j][0], _fmt(pj[j]['mean_site_distance_mm']),
                                                 _fmt(pj[j]['max_site_distance_mm']), _fmt(ref[j][2]), _fmt(ref[j][3]))
                                              for j in not_j)))
    w('')
    w('## %s: %d links, %d without a legal place, %d K footprints displaced against the rigid criterion of %d'
      % (FOCUS[0].replace('P100-N20 ', '20-circuit 1.00 mm links, ').replace('G-PER-2S', 'one ground per two signals'),
         head['links'], head['unplaced'], head['K_displaced']['total'], rig['total']))
    w('')
    w('The compact table for the ruling. Links per joint in the order JL to K / JR to K / P to K (with SUB and the EL '
      'pass-through) / JL to P through K. K displaced: footprints of K that a slot (both faces) or a K field (B.Cu) '
      'overlaps, at courtyard level, union over the placed links only. Front displaced: footprints under a front field on '
      'B.Cu, JL / JR / P. The rigid criterion of DS-41 is %d: %d K footprints in the post keep-outs (union of both faces in '
      '`../check-report.json`; DS-41 quotes 115) plus %d ST-08 part moves.'
      % (rig['total'], rig['post_keepout_K_footprints'], rig['st08_part_moves']))
    w('')
    w('| Option | Signals per link | Links | Per joint | Lower bound | Slots (share of K) | K by slots / fields only | '
      'K F.Cu / B.Cu | K total / criterion | Front JL / JR / P | No legal place | Cable needed, mm | Served by 50 mm '
      '(of placed) | Latch reach not shown |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for s in out['summary']:
        w(_option_row(s))
    w('')
    w('Counts cover the placed links only: an option with links that have no legal place would displace more. The post '
      'keep-outs stay in both designs; K footprints that the links displace outside them: %s.'
      % ', '.join('%s %d' % (s['option'], s['K_displaced']['outside_post_keepouts']) for s in out['summary']))
    w('')
    per_j = {j: [sum(1 for l in out['options'][s['option']]['links'] if l['joint'] == j and not l['placed'])
                 for s in out['summary']] for j in JOINTS}
    worst = max(JOINTS, key=lambda j: (sum(per_j[j]), j))
    w('## %s holds the most links without a legal place: %d to %d per option, of %d to %d unplaced in all'
      % (worst, min(per_j[worst]), max(per_j[worst]), min(s['unplaced'] for s in out['summary']),
         max(s['unplaced'] for s in out['summary'])))
    w('')
    lens = [z['field_length']['value'] for z in out['option_sizes']]
    w('Panel-hardware pins on the front board\'s B.Cu are forbidden for a field (project rule 1). The blockers listed '
      'per unplaced link below show which items rejected the most candidates; fields here are %.1f to %.1f mm long. '
      'Per option, links without a legal place by joint:' % (min(lens), max(lens)))
    w('')
    w('| Option | ' + ' | '.join(JOINTS) + ' |')
    w('| --- | --- | --- | --- | --- |')
    for s in out['summary']:
        d = out['options'][s['option']]['links']
        w('| %s | %s |' % (s['option'], ' | '.join(str(sum(1 for l in d if l['joint'] == j and not l['placed'])) for j in JOINTS)))
    w('')
    if small:
        _p_small(w, small, rig)
    for opt in FOCUS:
        d = out['options'][opt]['links']
        un = [l for l in d if not l['placed']]
        w('## %s: %d links have no legal place, each with its most frequent blocker in the search' % (opt, len(un)))
        w('')
        w('| Link | Centre | Signals | Candidates off a board or inside the edge web (of %d) | Most frequent blockers on the boards (candidates, smallest penetration mm) |'
          % (un[0]['blocked_in_search']['candidates'] if un else 0))
        w('| --- | --- | --- | --- | --- |')
        for l in un:
            mf = l['blocked_in_search']['most_frequent']
            w('| %s | %s | %d | %d | %s |' % (l['id'], _xy(l['centre']), l['signals'], l['blocked_in_search']['outside_a_board_or_edge_web'],
                                         '; '.join('%s (%d, %s)' % (m['blocker'], m['candidates'], _fmt(m['smallest_penetration_mm']))
                                                   for m in mf[:2])))
        w('')
        pl = [l for l in d if l['placed']]
        w('## %s: %d placed links and the K footprints each displaces' % (opt, len(pl)))
        w('')
        w('| Link | Slot centre | Cable direction | K by slot | K by field (B.Cu) | Front (B.Cu) | Cable needed mm | Latch reach |')
        w('| --- | --- | --- | --- | --- | --- | --- | --- |')
        for l in pl:
            ds = l['displaced']
            ks = sorted(set(ds['K F (slot)']) | set(ds['K B (slot)']))
            w('| %s | %s | %s | %s | %s | %s | %.1f | %s |' % (
                l['id'], _xy(l['slot_centre']), l['direction'], ', '.join(ks) or '-', ', '.join(ds['K B (field)']) or '-',
                len(ds['front B']), l['cable_needed_mm'],
                'open' if l['latch_reach']['verdict'] == 'open' else 'NOT SHOWN: ' + ', '.join(l['latch_reach']['neighbours_within_margin'])))
        w('')
    w('## Nets re-routed: every link signal moves on its front board and on K; sites lie up to %.1f mm from their front field'
      % max(v[1] for s in out['summary'] for v in s['site_to_field_mm'].values() if v[1] is not None))
    w('')
    w('| Option | Nets re-routed JL / JR / P / K | Site to front field, mean / largest mm: ' + ' / '.join(JOINTS) + ' |')
    w('| --- | --- | --- |')
    for s in out['summary']:
        n = s['nets_rerouted']
        w('| %s | %d / %d / %d / %d | %s |' % (s['option'], n['JL'], n['JR'], n['P'], n['K'],
                                             '; '.join('%s / %s' % (_fmt(v[0]), _fmt(v[1])) for v in (s['site_to_field_mm'][j] for j in JOINTS))))
    w('')
    w('Counts include the signals of links without a legal place; distances cover placed links only.')
    w('')
    served = all(s['links_served_by_cable'] == s['placed'] for s in out['summary'])
    needs = [x for s in out['summary'] if s['cable_needed_mm'] for x in s['cable_needed_mm']]
    w('## %s: the Z path needs %.1f to %.1f mm at the shortest field spacing'
      % ('A %g mm cable reaches every placed link' % head['cable_length_mm'] if served else
         '%d placed links need more than the %g mm cable' % (sum(s['placed'] - s['links_served_by_cable'] for s in out['summary']),
                                                             head['cable_length_mm']),
         min(needs), max(needs)))
    w('')
    w('Contacts: %s. Needed length = 2 x %s mm insertion + a + b + V + (pi - 4) x %s mm, with a = b = %s mm from each '
      'connector opening to the slot centre (%s mm straight stiffened tail, plus the %s mm bend radius; status in '
      '`link-options.json`) ' % (out['cable_contacts'], _fmt(sp['insertion_mm']), _fmt(sp['bend_radius_mm']),
                                 _fmt(sp['tail_run_mm']), _fmt(sp['straight_mm']), _fmt(sp['bend_radius_mm'])) +
      'and V = the front-board-to-K gap plus K\'s thickness, from the retained candidate. The %g to %g mm of spare length is a slack loop '
      'in the gap; whether it rests clear of the parts there is NOT RUN. The search keeps a and b at their minimum, so a '
      'cable never limits a placement in this study; a longer offset between the fields is not searched.'
      % (round(head['cable_length_mm'] - max(needs), 2), round(head['cable_length_mm'] - min(needs), 2)))
    w('')
    w('## The search is greedy and does not backtrack, so a link without a place may still have one under another order')
    w('')
    fx = sp['fixings']
    w('- Links in a fixed order (joint, link id). For each: every slot centre on a %s mm grid within %s mm of the '
      'link centre (ASSUMED), four cable directions.' % (_fmt(sp['step_mm']), _fmt(sp['radius_mm'])))
    w('- Fields: the front field lies inside the front board and the K field inside K (board-edge margin); neither lies '
      'on panel hardware, a hole, a fixing keep-out (%d posts, %d kept supports, %d other declared fixings), a tab or a '
      'SUB toggle on its face; the front field is not under an adapter outline or a kept selector envelope.'
      % (fx['posts'], fx['kept_supports'], fx['other_declared']))
    w('- Slot: grown by its %s mm web, it stays inside K and off holes, fixing keep-outs and the kept rigid pairs on '
      'both K faces, off other slots, and not under an adapter or a kept selector.' % _fmt(sp['slot_web_mm']))
    w('- Tails (the stiffened run of %s mm from each connector opening to the slot): screened against holes, fixing '
      'keep-outs (a post, or a sleeve with its screw head, nut and washer, stands in that run), tabs, SUB toggle pins and '
      'kept rigid pairs on the tail\'s face, and against fields, tails and slots of other links. The front tail is also '
      'screened against the adapters and kept selectors between the boards; the K tail runs behind K\'s rear face, '
      'where none of them is, so that screen does not apply to it. Panel pins and all other parts under a tail are '
      'only listed (`under_tails` in the candidate): whether they stand higher than the cable is a height question with '
      'no retained heights (NOT RUN).' % _fmt(sp['tail_run_mm']))
    w('- Cost = displaced footprints (front field, slot on both K faces, K field) + %s per mm of slot distance '
      '(ASSUMED). The cheapest legal candidate is kept and becomes an obstacle for later links. The counts are not '
      'minima.' % _fmt(sp['distance_weight_per_mm']))
    w('- A link without a legal candidate is reported with the blockers that rejected most candidates; it is not '
      'forced in. Another order, a wider radius or a different split of the sites may place more.')
    w('- The checker (`links.check`) re-evaluates every placed link under the same rules against all other placed '
      'links of its option, and adds capacity, site coverage and cable length.')
    w('- Latch reach: a K-rear footprint within %s mm (ASSUMED) of a K connector that no link displaces is listed; its '
      'height is not retained, so reach is NOT SHOWN there. The front end is plugged with K off and has open access in '
      'every placed case.' % _fmt(sp['latch_margin_mm']))
    w('')
    w('## Four assumed parameters move the result most: field envelope, clustering radius, ground-rule reading and tail length')
    w('')
    w('- The field envelopes, per size (status and source in `link-options.json`; courtyard growth ASSUMED, open '
      'actuator sweep in plan not dimensioned):')
    for z in out['option_sizes']:
        w('  - %s (%s): length %s mm = %s; depth %s mm = %s; stock cable %s.'
          % (z['id'], z['envelope'], _fmt(z['field_length']['value']), z['field_length']['formula'],
             _fmt(z['field_depth']['value']), z['field_depth']['formula'], z['stock_cable']['value']))
    w('- The clustering join radius (%s mm) and the order of the greedy search, which together set how many P links '
      'compete for the few windows between panel pins.' % _fmt(sp['join_radius_mm']))
    w('- The ground-rule reading: "a ground between every two signals" is taken without grounds at the outer edges.')
    w('- The fixed tail run a = b = %s mm and the slot of tail width + %s mm by %s mm with a %s mm web.'
      % (_fmt(sp['tail_run_mm']), _fmt(sp['slot_width_extra_mm']), _fmt(sp['slot_length_mm']), _fmt(sp['slot_web_mm'])))
    w('')
    w('## Checks NOT RUN')
    w('')
    w('- KiCad, DRC and `scripts/checks/regen-all.sh`: not admitted for this task (no board changes).')
    w('- Copper clearance, routing and the re-routed nets\' lengths: no stack board exists; nets re-routed are counted per '
      'board only.')
    w('- Heights under the tails, of the slack loops and of the K-rear neighbours of each latch: no retained heights.')
    w('- Tolerance, insertion force, coupling and ground current per contact (gate checks 3 and 4, ST-04).')
    w('- The exact connector identity (gate check 1, ST-01e).')
    w('')
    return '\n'.join(L) + '\n'


def _p_small(w, ps, rig):
    summ = ps['summary']
    best = next(s for s in summ if s['option'] == ps['best'])
    full = [s['option'] for s in summ if s['unplaced'] == 0]
    w('## Smaller stock links on the P joint: %d of %d P-only options place every link; the best, %s, places %d links '
      'and displaces %d K footprints' % (len(full), len(summ), best['option'], best['placed'], best['K_displaced']['total']))
    w('')
    w('Addition of attempt a5 (item 5), in `link-candidate-p-small.json`. Only the P joint is run (P to K with SUB and '
      'the EL pass-through, and JL to P through K); JL to K and JR to K are absent from these rows, so their K counts '
      'are the P joint\'s share alone. Best = %s. Same search, rules and parameters as the main rows; stock cable '
      'figures SOURCED from `design/stack/connectors/flex-links.json` block `st01e`.' % ps['best_rule'])
    w('')
    w('| Option | Links (P-K / JL-P) | No legal place | Slots | K displaced | Front JL / P | Cable needed mm | Stock cable '
      '(contacts, length) | Opposite-side only | Served / slack mm |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for s in summ:
        sc = s['stock_cable']
        w('| %s | %d / %d | %d | %d | %d | %d / %d | %s | %s | %s | %d of %d / %s |' % (
            s['option'], s['links_per_joint']['P-K'], s['links_per_joint']['JL-P via K'], s['unplaced'], s['slots'],
            s['K_displaced']['total'], s['front_displaced']['JL'], s['front_displaced']['P'],
            '%.1f to %.1f' % tuple(s['cable_needed_mm']) if s['cable_needed_mm'] else '-', sc['value'],
            'yes' if sc['opposite_side_only'] else 'no', sc['served'], s['placed'],
            '%.1f to %.1f' % tuple(sc['slack_mm']) if sc['slack_mm'] else '-'))
    w('')
    w('A stock cable longer than the needed length leaves the difference as a slack loop in the gap; where it rests is '
      'NOT RUN. Whether the Z path takes same-side or opposite-side contacts depends on the connector orientations '
      '(ST-01e `contact_sides`), so an opposite-side-only row needs a dual-contact part at one end or another path.')
    w('')
    cs = ps['combined']['summary']
    w('## With the best P option, all joints together: %s'
      % '; '.join('%s places %d of %d links and displaces %d K footprints against %d' % (
          s['option'], s['placed'], s['links'], s['K_displaced']['total'], rig['total']) for s in cs))
    w('')
    w('| Option | Links JL / JR / P / JL-P | No legal place per joint | Slots (share of K) | K slots / fields only | K total / criterion | Front JL / JR / P |')
    w('| --- | --- | --- | --- | --- | --- | --- |')
    for s in cs:
        k = s['K_displaced']
        w('| %s | %s | %s | %d (%.2f %%) | %d / %d | **%d** / %d | %d / %d / %d |' % (
            s['option'], ' / '.join(str(s['links_per_joint'][j]) for j in JOINTS),
            ' / '.join(str(s['unplaced_per_joint'][j]) for j in JOINTS), s['slots'], s['slot_area_share_of_K_pct'],
            k['by_slots'], k['by_fields_only'], k['total'], rig['total'],
            s['front_displaced']['JL'], s['front_displaced']['JR'], s['front_displaced']['P']))
    w('')
    fs = ps['field_scan']
    got = [r for r in fs['links'] if r['largest_circuits_placed'] is not None]
    lens = [r['field_length_mm'] for r in got]
    w('## %d P-joint links of %s have no legal place; with the other links fixed, %d of them find one with a field of '
      '%s to %s mm' % (len(fs['links']), fs['option'], len(got), _fmt(min(lens)) if lens else '-', _fmt(max(lens)) if lens else '-'))
    w('')
    w('Envelope: %s. Rule: %s.' % (fs['envelope'], fs['rule']))
    w('')
    w('| Link | Centre | Signals | Largest circuits that place | Field length mm | Slot centre |')
    w('| --- | --- | --- | --- | --- | --- |')
    for r in fs['links']:
        w('| %s | %s | %d | %s | %s | %s |' % (r['link'], _xy(r['centre']), r['signals'], _fmt(r['largest_circuits_placed']),
                                             _fmt(r['field_length_mm']), _xy(r['slot_centre']) if r['slot_centre'] else '-'))
    w('')
