"""Render design/stack/geometry/links/link-gate.md from link-gate.json. Headings carry the computed verdicts, and every
figure is read from the record (its `parameters`, `search`, `summary` and `links`), not written here."""

JOINT_NAMES = {'O-K': 'adapters to K', 'JL-K': 'JL to K', 'JR-K': 'JR to K', 'P-K': 'P to K (with SUB and EL)',
               'JL-P via K': 'JL to P through K'}


def _g(v):
    """A figure as recorded, to the precision it carries (no rounding to one decimal: findings 8 and 15)."""
    if v is None:
        return '-'
    if isinstance(v, float):
        return ('%.4f' % v).rstrip('0').rstrip('.')
    return str(v)


def _xy(v):
    return '(%s, %s)' % (_g(v[0]), _g(v[1]))


def _rng(v):
    return '-' if not v else '%s to %s' % (_g(v[0]), _g(v[1]))


def render(doc):
    s = doc['summary']
    s1 = doc['part_1']
    ls = [r for r in doc['links'] if not r.get('gone')]
    un = [r for r in ls if not r['placed']]
    un1 = [dict(r, **r['part_1_analysis']) for r in doc['links'] if r.get('way_out')]
    pl = [r for r in ls if r['placed']]
    total = doc['signals']['total']
    L = []
    w = L.append
    rp = doc['replacement']['totals']
    nopos = len(rp['without_a_position'])
    w('# Gate option of record, ST-02 a8 part 2: %s; %d displaced footprints, %d without a position'
      % ('%d of %d links without a place' % (len(un), len(ls)) if un else
         'every one of %d links has a legal place, %d of %d signals on them' % (len(ls), s['signals_on_placed_links'], total),
         len(doc['replacement']['footprints']), nopos))
    w('')
    w('Generated by `%s` from the option study\'s model and parameters, `link-gate-options.json`, the fixing list of '
      'ST-08 (`design/stack/fixings/fixing-sites.json`), the compliance map of ST-03 '
      '(`design/stack/mechanics/k-compliance-map.json`) and the class rules of `design/stack/link-electrical/inputs.json`; '
      'do not edit by hand. Status: %s. Courtyard level on unvalidated drafts: nothing here is a copper clearance, a '
      'tolerance result or a fit, no count is a minimum, and nothing is selected or adopted. The comparison runs of '
      'attempt a7 are retained unchanged in `link-gate-a7-comparisons.json` and the chain (a) to (d) of a8 part 1 in '
      '`link-gate-chain.json`; neither is regenerated by the tests.' % (doc['provenance']['regenerate'], doc['status']))
    w('')
    import links_gate_readme_part2 as r2
    r2.render(w, doc)
    w('# Placement of part 1 and the links of record')
    w('')
    w('The sections below describe the placement of part 1 and, where they read the links, the links that exist after '
      'part 2 (a link whose signals all ride on other links is no longer listed there).')
    w('')
    _signals(w, doc)
    _fixings(w, doc)
    _per_joint(w, s)
    _allocation(w, doc, ls)
    _refinement(w, doc)
    _unplaced(w, un1, total, s1)
    _why(w, doc, un1)
    _compliance(w, s, pl)
    _displaced(w, s)
    _latch(w, doc, s, pl)
    _tails(w, s, pl, doc)
    _cable(w, s, pl)
    _adapters(w, doc, ls)
    _rules(w, doc)
    w('## Checks NOT RUN')
    w('')
    w('- KiCad, DRC and `scripts/checks/regen-all.sh`: not admitted (no board changes).')
    w('- Copper clearance and routing, the coupling ratio per link at its actual order (ST-04 part 2), heights under the '
      'tails, of the loops and of the latch neighbours (no footprint height is retained), the open lock height and '
      'opening side (UNSOURCED), tolerance and insertion force.')
    w('- A full reordering or backtracking search: only the bounded improvement pass is run.')
    w('')
    return '\n'.join(L) + '\n'


def _signals(w, doc):
    sg = doc['signals']
    w('## %d signals go to links: %s' % (sg['total'], ', '.join('%d %s' % (v, k) for k, v in sg['by_class'].items())))
    w('')
    w('Per joint: %s. The class of each K-pair signal is derived from the class rules of '
      '`design/stack/link-electrical/inputs.json` (ASSUMED there); the adapter lines are STATIC (DS-79). The list per '
      'signal is `signals.classes` in `link-gate.json`.' % ', '.join('%s %d' % (JOINT_NAMES[j], v) for j, v in sg['by_joint'].items()))
    w('')


def _fixings(w, doc):
    f = doc['fixings']
    w('## %d fixings are keep-outs: %s' % (f['count'], ', '.join('%d %s' % (v, k) for k, v in f['by_kind'].items())))
    w('')
    w('Source: %s. Each keep-out stands on K and on its front board with the radii of the list; the term "fixing" in '
      'every screen of the option study (slot web, field, tail and slot on K and front) reads these circles in place '
      'of the keep-outs of `stack-candidate.json`.' % f['source'])
    w('')
    w('| Fixing | Kind | K centre | Front centre | Front board | Radius on K / front mm |')
    w('| --- | --- | --- | --- | --- | --- |')
    for x in f['keepouts']:
        w('| %s | %s | %s | %s | %s | %s / %s |' % (x['id'], x['kind'], _xy(x['K']), _xy(x['front']), x['front_board'],
                                                 _g(x['r_K']), _g(x['r_front'])))
    w('')
    for h in f['access_holes']:
        w('Access hole %s: %s mm in %s at %s for %s; %s. No link geometry lies on %s in this model.'
          % (h['id'], _g(h['diameter_mm']), h['board'], _xy(h['xy']), h['for'],
             'inside the keep-out of its sleeve on P' if h['inside_P_keepout_of_its_sleeve'] else 'NOT inside the keep-out of its sleeve on P',
             h['board']))
        w('')


def _per_joint(w, s):
    w('## Per joint and size: %d links, %d placed, %d grounds and %d unused positions on the placed links'
      % (s['links'], s['placed'], s['grounds'], s['unused_positions']))
    w('')
    w('| Joint | Size | Links | Placed | No place | Signals | Grounds | Unused positions |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    for j, sizes in s['per_joint_and_size'].items():
        for z in sorted(sizes, key=lambda k: -int(k.split('N')[1])):
            e = sizes[z]
            w('| %s | %s | %d | %d | %d | %d | %d | %d |' % (JOINT_NAMES[j], z, e['links'], e['placed'], e['unplaced'],
                                                          e['signals'], e['grounds'], e['unused']))
    w('')
    w('Signals, grounds and unused positions count all links of the row, placed or not. Totals of the placed links: '
      '%d slots, %d connectors and %d latches (one lock per connector).' % (s['slots'], s['connectors'], s['latches']))
    w('')


def _allocation(w, doc, ls):
    runs = [r for r in ls if any(p['kind'] == 'signal' and p['class'] == 'LOGIC' for p in r['positions'])
            and sum(1 for p in r['positions'] if p['kind'] == 'signal' and p['class'] == 'LOGIC') >= 2]
    w('## %d links carry a run of two or more LOGIC lines, each inside a ground on both sides and off the outer positions'
      % len(runs))
    w('')
    w('Allocation of DS-62 with DS-77 to DS-79 (rule text in `link-gate-options.json` `allocation`): an unused position '
      'is tied to AGND on both boards and counts as a ground; the outer signal positions go to a WIPER line first, then '
      'a single LOGIC line, then ANALOGUE, PRECISION last; each adapter link carries %s. The order per link is '
      '`positions`.' % ', '.join(doc['parameters']['adapter_order']))
    w('')


def _refinement(w, doc):
    rf = doc['search'].get('refinement')
    ls = doc['links']
    rows = [r for r in ls if 'refinement' in r]
    if not rf or not rows:
        return
    found = [r for r in rows if r['refinement']['found']]
    fg = rf['found_on_finer_grid']
    w('## %d of the %d links without a place on the %s mm grid find one under the unchanged rules: %s, '
      '%d by the improvement pass; %d remain'
      % (len(found), len(rows), _g(doc['search']['step_mm']),
         ' and '.join('%d on the %s mm grid' % (v, _g(float(k))) for k, v in fg.items()),
         rf['found_by_improvement_pass'], rf['remaining']))
    w('')
    w('Each link without a place on the %s mm grid is searched again in its order, every placed link fixed, on a %s mm '
      'grid, and on %s mm where its smallest miss there is below %s mm. Then at most %d rounds of the improvement pass: '
      '%s; allowance %s cost units above the cost before the pass (ASSUMED), at most %d candidates per link.'
      % (_g(doc['search']['step_mm']), _g(rf['grids_mm'][0]), _g(rf['grids_mm'][1]), _g(rf['quarter_grid_below_mm']),
         rf['improvement']['rounds'], rf['improvement']['rule'], _g(rf['improvement']['allowance']),
         rf['improvement']['candidates_per_link']))
    w('')
    w('| Link | Signals | Found | By | Grid mm | Slot centre | Direction | Moved link (old slot, cost before the pass -> new) |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    by_id = {r['id']: r for r in ls}
    for r in rows:
        f = r['refinement']
        mv = by_id.get(f.get('moved')) if f.get('moved') else None
        mvt = '-'
        if mv:
            m = [x for x in mv['moves_by_improvement'] if x['to_free_a_place_for'] == r['id']][-1]
            mvt = '%s (%s %s, %s -> %s)' % (mv['id'], _xy(m['slot_centre']), m['direction'], _g(m['cost_before_the_pass']),
                                             _g(m['new_cost']))
        w('| %s | %d | %s | %s | %s | %s | %s | %s |' % (
            r['id'], (r.get('part_1_analysis') or r)['signals'], 'yes' if f['found'] else '**no**', f.get('by', '-'),
            _g(f['grid_mm']) if f['found'] else ' / '.join(_g(g) for g in f['grids_tried_mm']),
            _xy(r['slot_centre']) if r['placed'] else '-', r.get('direction', '-') if r['placed'] else '-', mvt))
    w('')


def _unplaced(w, un, total, s):
    if not un:
        return
    sig = sum(r['signals'] for r in un)
    w('## %d links have no legal place under the screen of record and carry %d signals; they are the input of part 2'
      % (len(un), sig))
    w('')
    w('%d of %d signals are allocated to placed links. A link here goes to the ways out of DS-84 in part 2; whether a '
      'link gets a flex circuit (DS-59) is the design authority\'s decision. Nearest misses: the candidates nearest '
      'the link centre on the search grid against the final placed set, with the screen that rejects each; outline, '
      'K-edge and own-front-board rejections are left out.' % (s['signals_on_placed_links'], total))
    w('')
    w('| Link | Size | Centre | Signals (class, site) | Nearest misses (slot, direction: screen, penetration mm) | Most frequent screens |')
    w('| --- | --- | --- | --- | --- | --- |')
    for r in un:
        sigs = '; '.join('%s (%s, %s)' % (n, c, x['site']) for x in r.get('sites', []) for n, c in zip(x['signals'], x['classes']))
        w('| %s | %s | %s | %s | %s | %s |' % (
            r['id'], r['size'], _xy(r['centre']), sigs or '-',
            '; '.join('%s %s: %s (%s)' % (_xy(m['slot_centre']), m['direction'], m['screen'], _g(m['penetration_mm']))
                      for m in r.get('nearest_misses', [])) or '-',
            '; '.join('%s (%d)' % (b['blocker'], b['candidates']) for b in r.get('most_frequent_blockers', [])) or '-'))
    w('')


def _corr(c):
    if c is None:
        return '-'
    if c['free'] is not None:
        return '%s / %s' % (_g(c['free']), _g(c['needed']))
    lo, hi = c.get('gap_low_mm'), c.get('gap_high_mm')
    if lo is None and hi is None:
        return 'open both sides / %s' % _g(c['needed'])
    return 'open on one side, pad %s mm from the %s side / %s' % (_g(lo if lo is not None else hi),
                                                                 'low' if lo is not None else 'high', _g(c['needed']))


def _why(w, doc, un):
    rows = [r for r in un if 'why_no_place' in r]
    if not rows:
        return
    w('## Why %d links have no place: %s'
      % (len(rows), '; '.join('%s lacks %s%s' % (r['id'], r['why_no_place']['lacks'],
                                                 '' if r['why_no_place'].get('smallest_penetration_mm') is None else
                                                 ' by %s mm' % _g(r['why_no_place']['smallest_penetration_mm']))
                              for r in rows)))
    w('')
    w('On the finest grid searched for the link, against the final placed set: the deepest stage any candidate reaches '
      '(the field, the first %s mm of the tail, the rest of the front tail, the slot on K, the K side), the smallest '
      'penetration there with its screen (every rejection kept, also those without a depth), and the free corridor '
      'between panel-hardware pads through the field in x and y and across the first %s mm of the tail.'
      % (_g(doc['search']['tail_rule_hard_mm']), _g(doc['search']['tail_rule_hard_mm'])))
    w('')
    w('| Link | Lacks | Short by mm | Screen | Candidates at that stage | At (slot, direction, front extension mm) | Field corridor x: free / needed | Field corridor y | Tail corridor across |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for r in rows:
        y = r['why_no_place']
        c = y.get('field_corridor_mm', {})
        at = y.get('at')
        w('| %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            r['id'], y['lacks'], _g(y.get('smallest_penetration_mm')), y.get('blocker', '-'), _g(y.get('candidates_at_stage')),
            '%s %s, %s' % (_xy(at['slot_centre']), at['direction'], _g(at['front_extension_mm'])) if at else '-',
            _corr(c.get('x')), _corr(c.get('y')), _corr((y.get('tail_corridor_mm') or {}).get('across'))))
    w('')


def _compliance(w, s, pl):
    c = s['compliance']
    hi = c['links_above_list']
    w('## No K connector stands above %s mm/N; %d stand above %s mm/N (the other hand holds K\'s edge)'
      % (_g(c['limit_mm_per_N']), len(hi), _g(c['list_above_mm_per_N']))
      if not c['links_above_limit'] else '## %d K connectors stand above %s mm/N' % (len(c['links_above_limit']), _g(c['limit_mm_per_N'])))
    w('')
    w('The value of a K connector is the largest node value of the retained compliance map inside its K field grown by '
      'the map pitch on every side (DS-87); above %s mm/N a candidate is rejected by a hard screen. Largest value of '
      'the record: %s mm/N. DERIVED on the ASSUMED plate model of ST-03; nothing measured.'
      % (_g(c['limit_mm_per_N']), _g(c['max_mm_per_N'])))
    w('')
    if hi:
        w('| Link | K field centre | mm/N |')
        w('| --- | --- | --- |')
        for r in sorted((r for r in pl if r['id'] in hi), key=lambda r: -r['compliance_mm_per_N']):
            kc = r['geometry']['K_connector']
            w('| %s | %s | %s |' % (r['id'], _xy([(kc[0] + kc[2]) / 2, (kc[1] + kc[3]) / 2]), _g(r['compliance_mm_per_N'])))
        w('')


def _displaced(w, s):
    k = s['K_displaced']
    f = s['front_displaced']
    sp = k['split']
    w('## %d K footprints displaced, %d outside the keep-outs of the active fixings: %d ICs, %d resistors, %d capacitors, '
      '%d other' % (k['total'], k['outside_fixing_keepouts'], sp['ICs'], sp['resistors'], sp['capacitors'], sp['other']))
    w('')
    w('| Board and face | Footprints |')
    w('| --- | --- |')
    w('| K front (F.Cu), by slots | %d |' % k['F.Cu by slots'])
    w('| K rear (B.Cu), by slots | %d |' % k['B.Cu by slots'])
    w('| K rear (B.Cu), by fields | %d |' % k['B.Cu by fields'])
    w('| K rear (B.Cu), by the latch rule | %d (%d by that rule alone) |' % (k['B.Cu by the latch rule'], k['B.Cu by the latch rule alone']))
    for b, v in f.items():
        w('| %s rear (B.Cu), by front fields | %d |' % (b, v))
    w('')
    fs = s['front_displaced_split']
    w('Union over the placed links only; links without a place would displace more. Split by reference prefix (U, R, '
      'C, other). Front boards together: %d ICs, %d resistors, %d capacitors, %d other. The references are in `refs` '
      'of `link-gate.json`.' % (fs['ICs'], fs['resistors'], fs['capacitors'], fs['other']))
    w('')


def _latch(w, doc, s, pl):
    v = s['latch_verdicts']
    p = doc['parameters']
    w('## Latches of the %d placed links: %s' % (len(pl), ', '.join('%d %s' % (n, k) for k, n in v.items())))
    w('')
    w('Rule of DS-88: a footprint on K\'s rear face within %s mm of a K connector field and not under it is displaced '
      'like a footprint under the field, unless its package is exempt: %s (ASSUMED lower than the 2.0 mm connector '
      'body; no height is retained). The package is the footprint name of the K board file. %d K rear footprints are '
      'displaced by this rule alone. Verdict per latch: open (no neighbour), open after the displacement (every '
      'neighbour displaced by a link), NOT SHOWN with the reason (neighbours of an exempt package remain).'
      % (_g(p['latch_margin_mm']), '; '.join(p['latch_exempt']), s['K_displaced']['B.Cu by the latch rule alone']))
    w('')
    w('Packages met within the margin of the K fields: %s.' % ', '.join('%s %d' % kv for kv in s['latch_neighbour_packages'].items()))
    w('')


def _tails(w, s, pl, doc):
    p = doc['parameters']
    w('## %d front tails cross panel hardware beyond their first %s mm, with %d leads to trim to %s mm or less; '
      '%d placed links use a lengthened tail, %d have a place only because of it'
      % (s['front_tails_over_panel_hardware'], _g(doc['search']['tail_rule_hard_mm']), s['trim_leads'], _g(p['trim_to_mm']),
         s['lengthened_tails'], s['placed_only_with_lengthened_tail']))
    w('')
    w('Tail rule (DS-61, DS-84): no pad of panel hardware under the first %s mm of a front tail, counted from the front '
      'connector\'s courtyard edge; pads under the rest are allowed and listed. Tails are lengthened in steps of %s mm '
      'up to the spare of the cable.' % (_g(doc['search']['tail_rule_hard_mm']), _g(doc['search']['tail_step_mm'])))
    w('')
    w('| Link | Front board | Size | Front / K extension mm | Leads to trim |')
    w('| --- | --- | --- | --- | --- |')
    for r in pl:
        if r['trim_leads'] or r['lengthened_tail']:
            g = r['geometry']
            w('| %s | %s | %s | %s / %s%s | %s |' % (r['id'], r['front_board'], r['size'], _g(g['front_extension_mm']),
                                                  _g(g['K_extension_mm']), ' (needed)' if r['placed_only_with_lengthened_tail'] else '',
                                                  ', '.join(r['trim_leads']) or '-'))
    w('')


def _cable(w, s, pl):
    w('## Every placed link is within its cable: %s mm needed, loops of %s mm'
      % (_rng(s['cable_needed_mm']), _rng(s['loop_mm']))
      if not s['links_over_cable_length'] else
      '## %d placed links need more than their cable' % s['links_over_cable_length'])
    w('')
    w('Needed: the option study\'s rule (insertion on both ends, the tail runs a and b including any extension, the '
      'gap and the bend); the loop is the rest of the stock cable, a slack loop in the gap whose rest position is NOT RUN.')
    w('')
    w('| Link | Size | Cable | Slot centre | Direction | Needed mm | Loop mm | mm/N | Latch |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for r in pl:
        w('| %s | %s | %s %s mm | %s | %s | %s | %s | %s | %s |' % (
            r['id'], r['size'], r['cable'], _g(r['cable_length_mm']), _xy(r['slot_centre']), r['direction'],
            _g(r['cable_needed_mm']), _g(r['loop_mm']), _g(r['compliance_mm_per_N']), r['latch_reach']['verdict']))
    w('')


def _adapters(w, doc, ls):
    ad = [r for r in ls if r['joint'] == 'O-K']
    if not ad:
        return
    sizes = doc['parameters']['adapter_sizes']
    w('## %d of %d adapters place one %d-circuit link' % (sum(1 for r in ad if r['placed']), len(ad), sizes[0]['circuits']))
    w('')
    w('Each adapter link (DS-79): %s, tried in this order; front connector on the adapter\'s rear face, slot through K '
      'under the adapter, K connector on K\'s rear face. The six rigid K/O pairs, their K-side headers and their '
      'envelopes on K\'s front face are removed; an adapter without a place keeps its rigid pairs as the named '
      'exception of DS-64.' % '; '.join('%s on %s at %s mm' % (z['connector'], z['cable'], _g(z['cable_length_mm'])) for z in sizes))
    w('')
    w('| Adapter | Placed | Cable | Slot centre | Direction | Loop mm | K displaced |')
    w('| --- | --- | --- | --- | --- | --- | --- |')
    for r in ad:
        if r['placed']:
            d = r['displaced']
            k = sorted(set().union(*(set(v) for kk, v in d.items() if kk.startswith('K'))))
            w('| %s | yes | %s %s mm | %s | %s | %s | %s |' % (r['front_board'], r['cable'], _g(r['cable_length_mm']),
                                                            _xy(r['slot_centre']), r['direction'], _g(r['loop_mm']),
                                                            ', '.join(k) or '-'))
        else:
            w('| %s | no: the rigid pairs stay (named exception) | %s | - | - | - | - |' % (r['front_board'], ', '.join(r['cables_tried'])))
    w('')


def _rules(w, doc):
    sp, p = doc['search'], doc['parameters']
    w('## The rules this run uses')
    w('')
    w('- Field: FH12 at courtyard level, (0.5 n + 5.6) by %s mm with %s mm growth per side; tail 0.5 (n + 1) mm wide. '
      'Slot, cable path, search grid (%s mm within %s mm, four directions), margins and screens as in the option study.'
      % (_g(p['field_depth_mm']), _g(p['field_growth_mm']), _g(sp['step_mm']), _g(sp['radius_mm'])))
    w('- Sizes per joint: %s; on the P joint a link is clustered at the largest size and re-clustered from its own '
      'sites at the next smaller size where it finds no place. Adapters first, then JL to K, JR to K, P to K and JL to '
      'P through K. Clustering: the option study\'s greedy rule within %s mm with the feasibility of the allocation rule.'
      % ('; '.join('%s %s' % (k, '/'.join(str(x) for x in v)) for k, v in p['joints'].items()), _g(p['join_radius_mm'])))
    w('- Tails: per slot candidate the shortest legal front extension, then the shortest legal K extension, in steps '
      'of %s mm within the spare of the cable; cost = displaced footprints + %s x (slot distance + both extensions).'
      % (_g(sp['tail_step_mm']), _g(p['distance_weight_per_mm'])))
    w('- Compliance (DS-87): above %s mm/N on the map no K field is placed; above %s mm/N listed.'
      % (_g(p['compliance']['limit_mm_per_N']), _g(p['compliance']['list_above_mm_per_N'])))
    w('- The checker (`links_gate.check`) reads the run\'s inputs from `flags`, checks joint, front board, size and tail '
      'extensions against the sites, the ladder, the step and the spare, rebuilds every geometry, re-screens each '
      'placed link against all others with the screens of the search, recomputes the allocation, displaced lists, '
      'compliance values, trim lists, cable lengths and latch verdicts, and recomputes the nearest misses and blockers '
      'of every link without a place. It proves legality, not that a larger size or another order would not have placed.')
    w('')
