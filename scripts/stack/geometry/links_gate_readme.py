"""Render design/stack/geometry/links/link-gate.md from link-gate.json; headings carry the computed verdicts."""

JOINT_NAMES = {'O-K': 'adapters to K', 'JL-K': 'JL to K', 'JR-K': 'JR to K', 'P-K': 'P to K (with SUB and EL)',
               'JL-P via K': 'JL to P through K'}


def _fmt(v):
    return '-' if v is None else ('%.1f' % v if isinstance(v, float) else str(v))


def _xy(v):
    return '(%.1f, %.1f)' % tuple(v)


def _rng(v):
    return '-' if not v else '%.1f to %.1f' % tuple(v)


def render(doc):
    s = doc['summary']
    ls = doc['links']
    un = [r for r in ls if not r['placed']]
    pl = [r for r in ls if r['placed']]
    sig_total = doc['signals']['total']
    L = []
    w = L.append
    w('# Gate option on the FH12 field (ST-02 a7): %s; %d K footprints displaced'
      % ('%d of %d links have no legal place, %d of %d signals without a link' % (len(un), len(ls), sig_total - s['signals_on_placed_links'], sig_total)
         if un else 'every one of %d links has a legal place' % len(ls), s['K_displaced']['total']))
    w('')
    w('Generated by `python3 scripts/stack/geometry/links_gate.py` from the option study\'s model and parameters, '
      '`link-gate-options.json` and the class rules of `design/stack/link-electrical/inputs.json`; do not edit by hand. '
      'Status: the gate option of DS-67 without the fixing list of ST-08, the DS-44 JR lands and the re-placement '
      'search (attempt a8). Courtyard level on unvalidated drafts: nothing here is a copper clearance, a tolerance '
      'result or a fit, no count is a minimum, and nothing is selected. Parameter statuses are in '
      '`link-gate-options.json`.')
    w('')
    _field_change(w, doc)
    _signals(w, doc)
    _per_joint(w, s)
    _refinement(w, doc)
    _unplaced(w, un, sig_total, s)
    _why(w, doc, un)
    _sensitivity(w, doc)
    _displaced(w, s, doc)
    _tails(w, s, pl, doc)
    _cable(w, s, pl)
    _adapters(w, doc, ls)
    _causes(w, doc, s)
    _rules(w, doc)
    _handover(w)
    w('## Checks NOT RUN')
    w('')
    w('- The fixings of DS-66 as keep-outs, the DS-44 JR lands and the re-placement check of DS-60: attempt a8, after '
      'the fixing list of ST-08 is merged. The fixings here are the option study\'s %d (%s).'
      % (doc['fixings']['count'], ', '.join('%d %s' % (v, k) for k, v in doc['fixings']['by_kind'].items())))
    w('- KiCad, DRC and `scripts/checks/regen-all.sh`: not admitted (no board changes).')
    w('- Copper clearance and routing, the coupling ratio per link (ST-04), heights under the tails, of the loops and '
      'of the latch neighbours, the open lock height and opening side (UNSOURCED), tolerance and insertion force.')
    w('- A full reordering or backtracking search: only the bounded improvement pass of part 2 is run.')
    w('')
    return '\n'.join(L) + '\n'


def _field_change(w, doc):
    rows = doc.get('field_change')
    if not rows:
        return
    pairs = [(rows[i], rows[i + 1]) for i in range(0, len(rows), 2)]
    single = [(a, b) for a, b in pairs if not a['run'].startswith('JL/JR 40 + P')]
    w('## The FH12 field alone, under the option study\'s rules: %s'
      % '; '.join('%s %s places %d of %d links, %d K footprints (was %d)'
                  % (b['run'].replace(', ', ' at '), b['ground_rule'], b['placed'], b['links'], b['K_displaced'],
                     a['K_displaced']) for a, b in single))
    w('')
    w('Item 1: the option study\'s model, ground rules (one ground per two signals, G-PER-2S; a ground between every '
      'two, G-BETWEEN), clustering and search, with the FH12 field (0.5 n + 5.6 by 6.1 mm) in place of the study\'s '
      '0.5 n + 4.9 by 5.62 mm. Nothing else of the gate option is applied in these rows.')
    w('')
    w('| Run | Rule | Field (length by depth, mm) old -> FH12 | Links placed of all, old -> FH12 | K displaced old -> FH12 | Front JL / JR / P old -> FH12 |')
    w('| --- | --- | --- | --- | --- | --- |')
    for a, b in pairs:
        fa, fb = a['front_displaced'], b['front_displaced']
        w('| %s | %s | %s by %s -> %s by %s | %d of %d -> %d of %d | %d -> **%d** | %d / %d / %d -> %d / %d / %d |' % (
            a['run'], a['ground_rule'], _fmt(a['field_mm'][0]), _fmt(a['field_mm'][1]), _fmt(b['field_mm'][0]),
            _fmt(b['field_mm'][1]), a['placed'], a['links'], b['placed'], b['links'], a['K_displaced'], b['K_displaced'],
            fa['JL'], fa['JR'], fa['P'], fb['JL'], fb['JR'], fb['P']))
    w('')


def _signals(w, doc):
    sg = doc['signals']
    w('## %d signals go to links: %s' % (sg['total'], ', '.join('%d %s' % (v, k) for k, v in sg['by_class'].items())))
    w('')
    w('Per joint: %s. The class of each link signal is derived from the class rules of '
      '`design/stack/link-electrical/inputs.json` (ASSUMED there); the test suite asserts that the 490 K-pair '
      'classes equal the retained list of `design/stack/link-electrical/results.json`. The seven signals of each '
      'adapter have no retained class and are placed as ANALOGUE. The list per signal is `signals.classes` in '
      '`link-gate.json`.' % ', '.join('%s %d' % (JOINT_NAMES[j], v) for j, v in sg['by_joint'].items()))
    w('')


def _per_joint(w, s):
    w('## Per joint and size: %d links, %d placed, %d grounds and %d unused positions on the placed links'
      % (s['links'], s['placed'], s['grounds'], s['unused_positions']))
    w('')
    w('| Joint | Size | Links | Placed | No place | Signals | Grounds | Unused positions |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    for j, sizes in s['per_joint_and_size'].items():
        for z in sorted(sizes, key=lambda k: -int(k.split('N')[1])):
            e = sizes[z]
            w('| %s | %s | %d | %d | %d | %d | %d | %d |' % (JOINT_NAMES[j], z, e['links'], e['placed'], e['unplaced'],
                                                          e['signals'], e['grounds'], e['unused']))
    w('')
    w('Signals, grounds and unused positions count all links of the row, placed or not. Totals of the placed links: '
      '%d slots, %d connectors and %d latches (one lock per connector).' % (s['slots'], s['connectors'], s['latches']))
    w('')


def _unplaced(w, un, total, s):
    if not un:
        return
    sig = sum(r['signals'] for r in un)
    w('## %d links have no legal place under the unchanged rules and carry %d signals' % (len(un), sig))
    w('')
    w('%d of %d signals are allocated to placed links. Whether a link here gets a flex circuit (DS-59) is the design '
      'authority\'s decision. Each row: the link, its signals, its sites and the three candidates nearest its centre '
      'on the 2.0 mm grid with the screen that rejects each (slot centre, cable direction); `no_place` in '
      '`link-gate.json` names the size.' % (s['signals_on_placed_links'], total))
    w('')
    w('| Link | Centre | Signals | Sites | Nearest misses (screen, penetration mm) |')
    w('| --- | --- | --- | --- | --- |')
    for r in un:
        w('| %s | %s | %d | %s | %s |' % (
            r['id'], _xy(r['centre']), r['signals'], ', '.join(x['site'] for x in r.get('sites', [])) or '-',
            '; '.join('%s %s: %s (%s)' % (_xy(m['slot_centre']), m['direction'], m['screen'], _fmt(m['penetration_mm']))
                      for m in r['nearest_misses'])))
    w('')
    blk = {}
    for r in un:
        for b in r.get('most_frequent_blockers', [])[:1]:
            k = b['blocker'].split(' on ')[0] + (' on panel hardware' if 'panel hardware' in b['blocker'] else '')
            blk[k] = blk.get(k, 0) + 1
    if blk:
        w('Most frequent blocker in the search per link without a place: %s.'
          % ', '.join('%s (%d links)' % kv for kv in sorted(blk.items(), key=lambda kv: (-kv[1], kv[0]))))
        w('')


def _refinement(w, doc):
    rf = doc['search'].get('refinement')
    if not rf:
        return
    ls = doc['links']
    rows = [r for r in ls if 'refinement' in r]
    found = [r for r in rows if r['refinement']['found']]
    fg = rf['found_on_finer_grid']
    w('## %d of the %d links without a place on the 2.0 mm grid find one under the unchanged rules: %s, '
      '%d by the improvement pass; %d remain'
      % (len(found), len(rows), ' and '.join('%d on the %g mm grid' % (v, float(k)) for k, v in fg.items()),
         rf['found_by_improvement_pass'], rf['remaining']))
    w('')
    w('Part 2, item 1: each link without a place on the 2.0 mm grid is searched again, in its order and with every '
      'placed link fixed, on a %s mm grid, and on %s mm where its smallest miss there is below %s mm; rules, sizes, '
      'radius, cost and the 2.0 mm tail-extension step are unchanged. Then at most %d rounds of the improvement pass: '
      '%s; allowance %s cost units (ASSUMED). The refined placement is the gate option of record.'
      % ('%g' % rf['grids_mm'][0], '%g' % rf['grids_mm'][1], '%g' % rf['quarter_grid_below_mm'],
         rf['improvement']['rounds'], rf['improvement']['rule'], _fmt(rf['improvement']['allowance'])))
    w('')
    w('| Link (part 1) | Signals | Found | By | Grid mm | Slot centre | Direction | Moved link (old slot, cost old -> new) |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    moved = {r['id']: r for r in ls if 'moved_by_improvement' in r}
    for r in rows:
        f = r['refinement']
        mv = moved.get(f.get('moved'))
        mvt = '-' if not mv else '%s (%s %s, %s -> %s)' % (mv['id'], _xy(mv['moved_by_improvement']['slot_centre']),
                                                        mv['moved_by_improvement']['direction'],
                                                        '%.2f' % mv['moved_by_improvement']['cost'],
                                                        '%.2f' % mv['moved_by_improvement']['new_cost'])
        w('| %s | %d | %s | %s | %s | %s | %s | %s |' % (
            r['id'], r['signals'], 'yes' if f['found'] else '**no**', f.get('by', '-'),
            ('%g' % f['grid_mm']) if f['found'] else ' / '.join('%g' % g for g in f['grids_tried_mm']),
            '(%.2f, %.2f)' % tuple(r['slot_centre']) if r['placed'] else '-', r.get('direction', '-') if r['placed'] else '-', mvt))
    w('')


def _why(w, doc, un):
    rows = [r for r in un if 'why_no_place' in r]
    if not rows:
        return
    nl = doc.get('nearest_legal_unbounded', {})
    w('## Why %d links still have no place: %s'
      % (len(rows), '; '.join('%s lacks %s by %s mm' % (r['id'], r['why_no_place']['lacks'],
                                                      _f2(r['why_no_place'].get('smallest_penetration_mm'))) for r in rows)))
    w('')
    w('Part 2, item 2, on the finest grid searched for the link: the deepest screen stage any candidate reaches (the '
      'field, then the first %s mm of the tail, then the slot on K and the K side), the smallest penetration at that '
      'stage, and at that candidate the free corridor between the pads of the neighbouring panel hardware through the '
      'field in x and in y against the field\'s extent (0.5 n + 5.6 mm along the connector, 6.1 mm deep), and across '
      'the first %s mm of the tail against the tail width. "open" means no pad bounds that side within 30 mm. Nearest '
      'legal place: the same rules with the placed links fixed, unbounded over the front board (0.5 mm grid).'
      % (_fmt(doc['search']['tail_rule_hard_mm']), _fmt(doc['search']['tail_rule_hard_mm'])))
    w('')
    w('| Link | Lacks | Short by mm | Blocker | At (slot, direction, front extension) | Field corridor x: free / needed | Field corridor y: free / needed | Tail corridor across: free / needed | Nearest legal place |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for r in rows:
        y = r['why_no_place']
        c = y.get('field_corridor_mm', {})
        tc = (y.get('tail_corridor_mm') or {}).get('across')
        n = nl.get(r['id'])
        w('| %s | %s | %s | %s | %s %s, %s mm | %s / %s | %s / %s | %s | %s |' % (
            r['id'], y['lacks'], _f2(y.get('smallest_penetration_mm')), y.get('blocker', '-'),
            _xy(y['at']['slot_centre']) if 'at' in y else '-', y.get('at', {}).get('direction', ''),
            _fmt(y.get('at', {}).get('front_extension_mm')),
            _f2(c.get('x', {}).get('free')) if c.get('x', {}).get('free') is not None else 'open', _f2(c.get('x', {}).get('needed')),
            _f2(c.get('y', {}).get('free')) if c.get('y', {}).get('free') is not None else 'open', _f2(c.get('y', {}).get('needed')),
            ('%s / %s' % ('open' if tc['free'] is None else _f2(tc['free']), _f2(tc['needed']))) if tc else '-',
            ('%s mm at %s %s' % (_f2(n['distance_mm']), _xy(n['slot_centre']), n['direction'])) if n else 'none on the board'))
    w('')


def _sensitivity(w, doc):
    rows = doc.get('sensitivity')
    if not rows:
        return
    w('## Sensitivity, one ASSUMED term per run (comparisons, not results): %s'
      % '; '.join('%s leaves %d of the part-1 links without a place' % (r['step'], r['remaining_of_part1']) for r in rows))
    w('')
    w('Part 2, item 3: separate full runs with the refined search of the record, each changing one term; nothing is '
      'selected. "Of part 1" counts the links without a place on the 2.0 mm grid of the record whose sites are still on a '
      'link without a place. The 0 mm tail rule is the comparison row of part 1 (all links placed). The unbounded run '
      'searches the 2.0 mm grid over the whole front board and refines within 36 mm.')
    w('')
    w('| Run | Links | Placed | No place | Of part 1 without a place | K displaced | Leads to trim |')
    w('| --- | --- | --- | --- | --- | --- | --- |')
    for r in rows:
        w('| %s | %d | %d | %d | %d of %d | %d | %d |' % (r['step'], r['links'], r['placed'], r['unplaced'],
                                                       r['remaining_of_part1'], len(r['links_of_part1']), r['K_displaced'],
                                                       r['trim_leads']))
    w('')
    rad = [r for r in rows if 'radius' in r['step']]
    if rad:
        ids = [x['link'] for x in rad[0]['links_of_part1']]
        w('Slot distance from the link centre, per link of part 1, in the radius runs (mm; "-" = no place):')
        w('')
        w('| Link | ' + ' | '.join(r['step'] for r in rad) + ' |')
        w('| --- | ' + ' | '.join('---' for _ in rad) + ' |')
        for i, lid in enumerate(ids):
            w('| %s | %s |' % (lid, ' | '.join(_f2(r['links_of_part1'][i]['slot_distance_from_centre_mm']) for r in rad)))
        w('')


def _f2(v):
    return '-' if v is None else '%.2f' % v


def _displaced(w, s, doc):
    k = s['K_displaced']
    f = s['front_displaced']
    sp = k['split']
    w('## %d K footprints displaced, %d outside the post keep-outs: %d ICs, %d resistors, %d capacitors, %d other'
      % (k['total'], k['outside_post_keepouts'], sp['ICs'], sp['resistors'], sp['capacitors'], sp['other']))
    w('')
    w('| Board and face | Footprints |')
    w('| --- | --- |')
    w('| K front (F.Cu), by slots | %d |' % k['F.Cu by slots'])
    w('| K rear (B.Cu), by slots | %d |' % k['B.Cu by slots'])
    w('| K rear (B.Cu), by fields | %d |' % k['B.Cu by fields'])
    for b, v in f.items():
        w('| %s rear (B.Cu), by front fields | %d |' % (b, v))
    w('')
    fs = s['front_displaced_split']
    w('Union over the placed links only; links without a place would displace more. Split by reference prefix (U, R, '
      'C, other), as the ruling reported it. Front boards together: %d ICs, %d resistors, %d capacitors, %d other. '
      'The references are in `refs` of `link-gate.json`.' % (fs['ICs'], fs['resistors'], fs['capacitors'], fs['other']))
    w('')


def _tails(w, s, pl, doc):
    w('## %d front tails cross panel hardware beyond their first %.1f mm, with %d leads to trim to 1.0 mm or less; '
      '%d placed links use a lengthened tail, %d have a place only because of it'
      % (s['front_tails_over_panel_hardware'], doc['search']['tail_rule_hard_mm'], s['trim_leads'],
         s['lengthened_tails'], s['placed_only_with_lengthened_tail']))
    w('')
    w('Tail rule (DS-61, ASSUMED): no pad of panel hardware under the first %.1f mm of a front tail, counted from the '
      'front connector\'s courtyard edge; pads under the rest are allowed and listed. Tails are lengthened in steps of '
      '%s mm up to the spare of the cable.' % (doc['search']['tail_rule_hard_mm'], _fmt(doc['search']['tail_step_mm'])))
    w('')
    w('| Link | Front board | Size | Front / K extension mm | Leads to trim |')
    w('| --- | --- | --- | --- | --- |')
    for r in pl:
        if r['trim_leads'] or r['lengthened_tail']:
            g = r['geometry']
            w('| %s | %s | %s | %s / %s%s | %s |' % (r['id'], r['front_board'], r['size'], _fmt(g['front_extension_mm']),
                                                  _fmt(g['K_extension_mm']), ' (needed)' if r['placed_only_with_lengthened_tail'] else '',
                                                  ', '.join(r['trim_leads']) or '-'))
    w('')


def _cable(w, s, pl):
    w('## Every placed link is within its cable: %s mm needed, loops of %s mm; %d latches have a rear neighbour within 1.0 mm'
      % (_rng(s['cable_needed_mm']), _rng(s['loop_mm']), s['latch_not_shown'])
      if not s['links_over_cable_length'] else
      '## %d placed links need more than their cable' % s['links_over_cable_length'])
    w('')
    w('Needed = 2 x 4.0 mm insertion + a + b + V + (pi - 4) x 2.4 mm (the option study\'s rule), with a and b the '
      'front and K tail runs including any extension; the loop is the rest of the stock cable, a slack loop in the gap '
      'whose rest position is NOT RUN. Latch reach: a K-rear footprint within 1.0 mm (ASSUMED) of a K connector that '
      'no link displaces; its height is not retained, so reach is NOT SHOWN there.')
    w('')
    w('| Link | Size | Cable | Slot centre | Direction | Needed mm | Loop mm | Latch neighbours |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    for r in pl:
        w('| %s | %s | %s %g mm | %s | %s | %.1f | %.1f | %s |' % (
            r['id'], r['size'], r['cable'], r['cable_length_mm'], _xy(r['slot_centre']), r['direction'],
            r['cable_needed_mm'], r['loop_mm'], ', '.join(r['latch_reach']['neighbours_within_margin']) or '-'))
    w('')


def _adapters(w, doc, ls):
    ad = [r for r in ls if r['joint'] == 'O-K']
    if not ad:
        return
    small = {x['adapter']: x for x in doc['adapters_at_8']}
    ok8 = sum(1 for x in small.values() if all(v['places'] for k, v in x.items() if k != 'adapter'))
    w('## %d of %d adapters place one 14-circuit link; 8 circuits place on %d of them'
      % (sum(1 for r in ad if r['placed']), len(ad), ok8))
    w('')
    w('Each adapter link (DS-64): front connector on the adapter\'s rear face, slot through K under the adapter, '
      'K connector on K\'s rear face; gap 13.0 mm. The six rigid K/O pairs, their K-side headers and their envelopes on '
      'K\'s front face are removed; the selector pins on the adapter\'s rear face are panel hardware. The adapter outline '
      'and the selector envelope stay as screens for every other link; the adapter\'s own link passes under both, as the '
      'rigid pairs did (ASSUMED reading of DS-64). The 8-circuit check is run with every other link fixed and reads the '
      'seven lines as static (one ground), which holds only if ST-04 finds them static.')
    w('')
    w('| Adapter | Placed (14) | Slot centre | Direction | Loop with 50 mm | K displaced | 8 circuits: loop with C29534 50 mm / C81339 40 mm |')
    w('| --- | --- | --- | --- | --- | --- | --- |')
    for r in ad:
        x = small.get(r['front_board'], {})
        k8 = ' / '.join(('%.1f' % v['loop_mm']) if v['places'] else 'no place' for k, v in x.items() if k != 'adapter')
        if r['placed']:
            d = r['displaced']
            k = sorted(set(d['K F (slot)']) | set(d['K B (slot)']) | set(d['K B (field)']))
            w('| %s | yes | %s | %s | %.1f | %s | %s |' % (r['front_board'], _xy(r['slot_centre']), r['direction'],
                                                       r['loop_mm'], ', '.join(k) or '-', k8))
        else:
            w('| %s | no: the rigid pairs stay (named exception) | - | - | - | - | %s |' % (r['front_board'], k8))
    w('')


def _causes(w, doc, s):
    steps = doc.get('causes')
    if not steps:
        return
    fc = {r['run']: r for r in doc.get('field_change', []) if r['field'] == 'FH12 field'}
    row88 = fc.get('JL/JR 40 + P 8 (the 88-link row)')
    last = steps[-2]
    w('## Against the ruling\'s rows (63 links with 215 K footprints; 88 with 295), on the 2.0 mm grid of part 1: %d links, %d placed, %d K footprints'
      % (last['links'], last['placed'], last['K_displaced']))
    w('')
    w('One cause at a time, each row adding one change to the one above (separate full runs on the 2.0 mm grid of part 1, '
      'without the refinement of part 2; greedy, not minima). The first two rows are the option study\'s engine; from '
      'the third on, the gate engine with the FH12 field and the class rule of DS-62. The refined gate option of record '
      'has %d links, %d placed and %d K footprints.' % (s['links'], s['placed'], s['K_displaced']['total']))
    w('')
    w('| Step | Links | Placed | No place | K displaced | Front JL / JR / P | Lengthened tails | Tails over panel hardware |')
    w('| --- | --- | --- | --- | --- | --- | --- | --- |')
    base = next((r for r in doc.get('field_change', []) if r['run'].startswith('JL/JR 40 + P 8 (the 88')
                 and r['field'] == 'option study field'), None)
    if base:
        f = base['front_displaced']
        w('| Ruling\'s 88-link row recomputed (a6 code; the ruling read 295 at a5) | %d | %d | %d | %d | %d / %d / %d | - | - |'
          % (base['links'], base['placed'], base['unplaced'], base['K_displaced'], f['JL'], f['JR'], f['P']))
    if row88:
        f = row88['front_displaced']
        w('| FH12 field (study rule: a ground between every two) | %d | %d | %d | %d | %d / %d / %d | - | - |'
          % (row88['links'], row88['placed'], row88['unplaced'], row88['K_displaced'], f['JL'], f['JR'], f['P']))
    for st in steps:
        f = st['front_displaced']
        w('| %s | %d | %d | %d | %d | %d / %d / %d | %d | %d |' % (
            st['step'], st['links'], st['placed'], st['unplaced'], st['K_displaced'], f['JL'], f['JR'], f['P'],
            st['lengthened_tails'], st['tails_over_panel_hardware']))
    w('')
    tr = steps[-1]
    if 'trim_leads' in tr:
        w('The last row is not a step: it lifts the 4.0 mm rule from the gate option, the trade DS-61 names if links lose '
          'their place; its front tails then cross %d panel-hardware leads to trim.' % tr['trim_leads'])
        w('')
